-- Company Builds: run once in the new Supabase project (SQL Editor -> New query -> Run)

create table if not exists public.builds (
  id bigint generated by default as identity primary key,
  company_name text not null,
  company_code text,
  hierarchy text,
  status text default 'Pending',
  completion_date date,
  due_date date,
  built_by text,
  assigned_by text,
  qc_by text,
  qc_status text,
  created_at timestamptz default now()
);

create table if not exists public.build_checks (
  build_id bigint not null references public.builds(id),
  item_id text not null,
  built boolean default false,
  qc boolean default false,
  na boolean default false,
  primary key (build_id, item_id)
);

-- The app can read, add and edit, but not delete
alter table public.builds enable row level security;
alter table public.build_checks enable row level security;
create policy "builds read"  on public.builds for select to anon, authenticated using (true);
create policy "builds add"   on public.builds for insert to anon, authenticated with check (true);
create policy "builds edit"  on public.builds for update to anon, authenticated using (true) with check (true);
create policy "checks read"  on public.build_checks for select to anon, authenticated using (true);
create policy "checks add"   on public.build_checks for insert to anon, authenticated with check (true);
create policy "checks edit"  on public.build_checks for update to anon, authenticated using (true) with check (true);

notify pgrst, 'reload schema';
